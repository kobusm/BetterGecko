#!/usr/bin/env python3
"""Creates the Play upload key for BetterGecko and builds a signed release bundle.

Run it yourself, in a terminal:

    python3 scripts/make_upload_key.py

What it does:
  1. Creates ~/Keys/bettergecko-upload.jks (refuses to overwrite an existing key).
  2. Writes android/keystore.properties (gitignored, readable only by you).
  3. Builds android/app/build/outputs/bundle/release/app-release.aab.
  4. Checks that the bundle is signed with the new key, and prints its fingerprint.

The password is read with getpass, so it never echoes, and it reaches keytool through
an environment variable (keytool's `:env` form) rather than the command line, where
any other process could read it from `ps`.

It is safe to re-run: with a key already in place it skips straight to the build.
"""
import getpass
import os
import stat
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ANDROID = REPO / "android"
PROPERTIES = ANDROID / "keystore.properties"
BUNDLE = ANDROID / "app/build/outputs/bundle/release/app-release.aab"
KEYSTORE = Path.home() / "Keys" / "bettergecko-upload.jks"
ALIAS = "upload"
JAVA_HOME = Path("/opt/homebrew/opt/openjdk@17")
KEYTOOL = JAVA_HOME / "bin" / "keytool"
JARSIGNER = JAVA_HOME / "bin" / "jarsigner"
MIN_PASSWORD = 8  # keytool rejects anything shorter than 6; be a bit stricter


def fail(message: str) -> None:
    print(f"\n✗ {message}", file=sys.stderr)
    sys.exit(1)


def step(message: str) -> None:
    print(f"\n▸ {message}")


def ask_password() -> str:
    while True:
        first = getpass.getpass("Choose a keystore password: ")
        if len(first) < MIN_PASSWORD:
            print(f"  Use at least {MIN_PASSWORD} characters.")
            continue
        if first != getpass.getpass("Type it again: "):
            print("  They don't match, try again.")
            continue
        return first


def ask(prompt: str, default: str) -> str:
    answer = input(f"{prompt} [{default}]: ").strip()
    return answer or default


def distinguished_name() -> str:
    """The certificate's owner fields. Google doesn't display them; they only need to be valid."""
    print("\nCertificate details (press Enter to accept the default):")
    name = ask("  Your name", "Kobus Marneweck")
    country = ask("  Two-letter country code", "ZA").upper()
    if len(country) != 2 or not country.isalpha():
        fail("Country code must be two letters, e.g. ZA or US.")
    # Commas and backslashes are special in an X.500 name; escape them.
    escape = lambda s: s.replace("\\", "\\\\").replace(",", "\\,")
    return f"CN={escape(name)}, C={country}"


def create_keystore(password: str) -> None:
    step(f"Creating {KEYSTORE}")
    KEYSTORE.parent.mkdir(mode=0o700, exist_ok=True)
    env = {**os.environ, "BETTERGECKO_KS_PASS": password}
    subprocess.run(
        [
            str(KEYTOOL), "-genkeypair", "-v",
            "-keystore", str(KEYSTORE),
            "-alias", ALIAS,
            "-keyalg", "RSA", "-keysize", "2048",
            # ~27 years. Play requires validity well past 2033.
            "-validity", "10000",
            "-dname", distinguished_name(),
            "-storetype", "PKCS12",
            # PKCS12 uses one password for the store and the key.
            "-storepass:env", "BETTERGECKO_KS_PASS",
            "-keypass:env", "BETTERGECKO_KS_PASS",
        ],
        env=env,
        check=True,
    )
    KEYSTORE.chmod(stat.S_IRUSR | stat.S_IWUSR)


def write_properties(password: str) -> None:
    step(f"Writing {PROPERTIES.relative_to(REPO)}")
    # Java .properties treats backslash as an escape character, so double it.
    escaped = password.replace("\\", "\\\\")
    # Create it already restricted, so the password is never briefly world-readable.
    fd = os.open(PROPERTIES, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(
            "# Generated by scripts/make_upload_key.py. Gitignored; never commit it.\n"
            f"storeFile={KEYSTORE}\n"
            f"storePassword={escaped}\n"
            f"keyAlias={ALIAS}\n"
            f"keyPassword={escaped}\n"
        )


def password_opens_keystore(password: str) -> bool:
    env = {**os.environ, "BETTERGECKO_KS_PASS": password}
    result = subprocess.run(
        [str(KEYTOOL), "-list", "-keystore", str(KEYSTORE), "-alias", ALIAS,
         "-storepass:env", "BETTERGECKO_KS_PASS"],
        env=env, capture_output=True, text=True,
    )
    return result.returncode == 0


def properties_need_password() -> bool:
    """Missing, or still holding the template's placeholders."""
    return not PROPERTIES.exists() or "CHANGE_ME" in PROPERTIES.read_text()


def adopt_existing_keystore() -> None:
    """A key made earlier (e.g. by hand): ask for its password, prove it, then record it."""
    print("keystore.properties has no real password yet, so I need the one you chose for that key.")
    for _ in range(3):
        password = getpass.getpass("Keystore password: ")
        if password_opens_keystore(password):
            write_properties(password)
            return
        print("  That password doesn't open the key, or it has no 'upload' alias. Try again.")
    fail(
        "Couldn't open the key after three tries. If the password is truly lost, move "
        f"{KEYSTORE} aside and re-run to create a new one (only safe before your first upload)."
    )


def check_gitignored() -> None:
    result = subprocess.run(
        ["git", "check-ignore", "-q", str(PROPERTIES)], cwd=REPO
    )
    if result.returncode != 0:
        fail(f"{PROPERTIES.name} is not gitignored. Refusing to continue with a password in it.")


def build_bundle() -> None:
    step("Building the signed release bundle (several minutes; quit the emulator first if it's running)")
    env = {**os.environ, "JAVA_HOME": str(JAVA_HOME)}
    subprocess.run(["./gradlew", "bundleRelease", "--console=plain", "-q"], cwd=ANDROID, env=env, check=True)
    if not BUNDLE.exists():
        fail(f"The build finished but {BUNDLE} is missing.")


def verify_bundle() -> None:
    step("Checking the bundle's signature")
    result = subprocess.run(
        [str(JARSIGNER), "-verify", str(BUNDLE)], capture_output=True, text=True
    )
    if "jar verified" not in result.stdout:
        fail("The bundle is not signed. Is keystore.properties correct?\n" + result.stdout + result.stderr)
    cert = subprocess.run(
        [str(KEYTOOL), "-printcert", "-jarfile", str(BUNDLE)], capture_output=True, text=True, check=True
    ).stdout
    fingerprint = next((line.strip() for line in cert.splitlines() if "SHA256:" in line), "")
    print(f"  Signed. {fingerprint}")


def main() -> None:
    if not KEYTOOL.exists():
        fail(f"keytool not found at {KEYTOOL}. Install JDK 17: brew install openjdk@17")

    if KEYSTORE.exists():
        print(f"An upload key already exists at {KEYSTORE}; not creating another.")
        # A key created by hand is world-readable by default; tighten it.
        KEYSTORE.chmod(stat.S_IRUSR | stat.S_IWUSR)
        if properties_need_password():
            adopt_existing_keystore()
    else:
        print("This creates the BetterGecko Play upload key.")
        print("Save the password in your password manager as soon as you've chosen it.\n")
        password = ask_password()
        create_keystore(password)
        write_properties(password)
        del password

    check_gitignored()
    build_bundle()
    verify_bundle()

    print(f"""
✓ Done. Upload this file to Play Console:
  {BUNDLE}

Now back up {KEYSTORE} somewhere safe and off this Mac (e.g. as an attachment in your
password manager). With Play App Signing a lost upload key can be reset through Google,
but that takes days.""")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as e:
        fail(f"{Path(e.cmd[0]).name} failed (exit {e.returncode}). See its output above.")
    except KeyboardInterrupt:
        fail("Cancelled.")
